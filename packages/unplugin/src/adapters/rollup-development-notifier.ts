import { readFile } from 'node:fs/promises';
import { resolve } from 'node:path';

import { moduleId } from '../core/options';
import type { CssxPluginOptions } from '../core/options';
import { developmentPluginOptions } from '../core/options';
import { sourceSignature } from '../core/source-signature';
import { compileCssxStylesheet, cssWithSourceMapComment } from '../native/stylesheet';
import type { ModuleCssxData } from '../transforms/module-cssx-data';
import { updateProjectScanModule } from '../transforms/project-scan';
import { startDevelopmentCoordinator } from './development-coordinator';
import { publishNextDevelopmentStylesheet } from './next-development-server';
import type { NextDevelopmentHmrConnection } from './next-development-server';
import { startNextDevelopmentServer, stopNextDevelopmentServer } from './next-development-server';

/** Maximum eager Rollup transforms retained until the corresponding watch rebuild. */
const MAX_PREPARED_ROLLUP_TRANSFORMS = 64;
/** Maximum estimated generated bytes retained in prepared Rollup transforms. */
const MAX_PREPARED_ROLLUP_BYTES = 16 * 1024 * 1024;
/** Maximum changed modules queued for serial eager processing. */
const MAX_PENDING_ROLLUP_UPDATES = 256;

/** Settings needed to publish cached Rollup stylesheet metadata during watch mode. */
export interface RollupDevelopmentNotifierOptions {
  /** CSS asset filename used for the source map comment. */
  readonly cssFileName: string;
  /** Reads the active theme source. */
  readonly getTheme: () => Promise<string | undefined>;
  /** Returns the active stylesheet transport after startup. */
  readonly getConnection: () =>
    NextDevelopmentHmrConnection | undefined | Promise<NextDevelopmentHmrConnection | undefined>;
  /** Whether the initial watch build has completed. */
  readonly isReady: () => boolean;
  /** Development compiler options. */
  readonly options: CssxPluginOptions;
  /** Whether to emit a CSS source map. */
  readonly sourceMap: boolean;
  /** Transformed source metadata retained by this plugin instance. */
  readonly dataById: Map<string, ModuleCssxData>;
}

/** Coalesces Rollup watch updates and publishes only distinct stylesheet revisions. */
export function createRollupDevelopmentNotifier(configuration: RollupDevelopmentNotifierOptions) {
  let revision = 0;
  let pending: Promise<void> | undefined;
  let publishedStylesheet: string | undefined;
  return (): Promise<void> => {
    if (!configuration.isReady()) {
      return Promise.resolve();
    }
    revision++;
    if (!pending) {
      pending = new Promise<void>((resolveNotify) => setImmediate(resolveNotify))
        .then(async () => {
          let publishedRevision = -1;
          do {
            publishedRevision = revision;
            const connection = await configuration.getConnection();
            if (!connection) {
              return;
            }
            const options = developmentPluginOptions(configuration.options);
            const stylesheet = await compileCssxStylesheet(
              [...configuration.dataById.values()],
              await configuration.getTheme(),
              options.layer,
              configuration.sourceMap,
              options.darkMode,
              options.preflight,
            );
            const css = cssWithSourceMapComment(stylesheet, configuration.cssFileName);
            if (css !== publishedStylesheet) {
              await publishNextDevelopmentStylesheet(connection, css);
              publishedStylesheet = css;
            }
          } while (publishedRevision !== revision);
        })
        .catch((error: unknown) => {
          console.warn(
            `CSSX: Rollup stylesheet update failed: ${error instanceof Error ? error.message : String(error)}`,
          );
        })
        .finally(() => {
          pending = undefined;
        });
    }
    return pending;
  };
}

/** Owns the watch lifecycle and stylesheet transport for one Rollup development build. */
export function createRollupDevelopmentRuntime<TTransformResult>(
  configuration: Omit<RollupDevelopmentNotifierOptions, 'getConnection' | 'isReady'> & {
    readonly root: string;
    readonly transformSource: (source: string, id: string) => Promise<TTransformResult>;
  },
) {
  const stylesheetFile = resolve(configuration.root, '.cssx/rollup.css');
  let started = false;
  let ready = false;
  let connection: NextDevelopmentHmrConnection | undefined;
  let coordinatorStartup: Promise<() => void> | undefined;
  let active = true;
  const prepared = new Map<
    string,
    { readonly sourceSignature: string; readonly result: TTransformResult; readonly size: number }
  >();
  let preparedBytes = 0;
  const pendingUpdates = new Map<string, string>();
  let updateQueue: Promise<void> | undefined;
  const removePrepared = (id: string) => {
    const previous = prepared.get(id);
    if (previous) {
      preparedBytes -= previous.size;
      prepared.delete(id);
    }
  };
  const preparedSize = (result: TTransformResult): number => {
    if (typeof result === 'string') {
      return result.length * 2;
    }
    if (!result || typeof result !== 'object') {
      return 0;
    }
    const output = result as { readonly code?: unknown; readonly map?: unknown };
    const codeBytes = typeof output.code === 'string' ? output.code.length * 2 : 0;
    const mapBytes = output.map === undefined ? 0 : (JSON.stringify(output.map)?.length ?? 0) * 2;
    return codeBytes + mapBytes;
  };
  const cachePrepared = (id: string, source: string, result: TTransformResult) => {
    const size = preparedSize(result);
    if (size > MAX_PREPARED_ROLLUP_BYTES) {
      removePrepared(id);
      return;
    }
    removePrepared(id);
    while (prepared.size >= MAX_PREPARED_ROLLUP_TRANSFORMS || preparedBytes + size > MAX_PREPARED_ROLLUP_BYTES) {
      const oldestId = prepared.keys().next().value;
      /* v8 ignore next -- A non-empty prepared map is required to reach this loop. */
      if (oldestId === undefined) {
        break;
      }
      removePrepared(oldestId);
    }
    prepared.set(id, { sourceSignature: sourceSignature(source), result, size });
    preparedBytes += size;
  };
  const notify = createRollupDevelopmentNotifier({
    ...configuration,
    getConnection: () => connection,
    isReady: () => ready,
  });
  const updateCssOnlySourceNow = async (id: string): Promise<void> => {
    const normalizedId = moduleId(id);
    const previous = configuration.dataById.get(normalizedId);
    if (!active || !previous?.cssOnlySignature) {
      return;
    }
    try {
      const source = await readFile(normalizedId, 'utf8');
      if (prepared.get(normalizedId)?.sourceSignature === sourceSignature(source)) {
        return;
      }
      const result = await configuration.transformSource(source, id);
      const updated = configuration.dataById.get(normalizedId);
      if (!updated || updated.cssOnlySignature !== previous.cssOnlySignature) {
        removePrepared(normalizedId);
        return;
      }
      cachePrepared(normalizedId, source, result);
      await notify();
    } catch (error) {
      if ((error as NodeJS.ErrnoException).code !== 'ENOENT') {
        console.warn(
          `CSSX: Rollup stylesheet update failed: ${error instanceof Error ? error.message : String(error)}`,
        );
      }
    }
  };
  const updateCssOnlySource = (id: string): Promise<void> => {
    if (!active) {
      return Promise.resolve();
    }
    const normalizedId = moduleId(id);
    if (!pendingUpdates.has(normalizedId) && pendingUpdates.size >= MAX_PENDING_ROLLUP_UPDATES) {
      return Promise.resolve();
    }
    pendingUpdates.set(normalizedId, id);
    if (!updateQueue) {
      updateQueue = (async () => {
        while (active && pendingUpdates.size > 0) {
          const next = pendingUpdates.entries().next().value as [string, string] | undefined;
          /* v8 ignore next -- The loop condition requires at least one pending update. */
          if (!next) {
            break;
          }
          pendingUpdates.delete(next[0]);
          await updateCssOnlySourceNow(next[1]);
        }
      })().finally(() => {
        updateQueue = undefined;
        const pending = pendingUpdates.values().next().value as string | undefined;
        if (active && pending !== undefined) {
          void updateCssOnlySource(pending);
        }
      });
    }
    return updateQueue;
  };
  return {
    buildStart() {
      if (started) {
        return;
      }
      started = true;
      connection = startNextDevelopmentServer(configuration.root, stylesheetFile);
      coordinatorStartup = startDevelopmentCoordinator(
        configuration.root,
        stylesheetFile,
        developmentPluginOptions(configuration.options),
        connection,
      );
      void coordinatorStartup.catch((error: unknown) => {
        console.warn(`CSSX: Rollup development coordinator failed: ${String(error)}`);
      });
    },
    buildEnd() {
      ready = true;
    },
    closeWatcher: async () => {
      await coordinatorStartup?.then(
        (stop) => stop(),
        () => undefined,
      );
      active = false;
      pendingUpdates.clear();
      prepared.clear();
      preparedBytes = 0;
      if (connection) {
        stopNextDevelopmentServer(configuration.root);
      }
      connection = undefined;
      coordinatorStartup = undefined;
      started = false;
      ready = false;
    },
    getConnection: () => connection,
    takePrepared(id: string, source: string): { readonly handled: boolean; readonly result?: TTransformResult } {
      const normalizedId = moduleId(id);
      const value = prepared.get(normalizedId);
      if (!value || value.sourceSignature !== sourceSignature(source)) {
        return { handled: false };
      }
      removePrepared(normalizedId);
      return { handled: true, result: value.result };
    },
    onTransformed(id: string): void {
      removePrepared(moduleId(id));
    },
    async delete(id: string): Promise<void> {
      const normalizedId = moduleId(id);
      removePrepared(normalizedId);
      await updateProjectScanModule(
        configuration.root,
        normalizedId,
        developmentPluginOptions(configuration.options),
        null,
      );
    },
    updateCssOnlySource,
    notifyStyles: () => notify(),
  };
}
